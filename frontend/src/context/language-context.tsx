interface LanguageContextValue {
    language: ResidentLanguage;
    setLanguage: (language: ResidentLanguage) => void;
    t: (source: string) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
    language: 'en',
    setLanguage: () => undefined,
    t: (source) => source,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
    const [language, setLanguageState] = useState<ResidentLanguage>(() => {
        try {
            return window.localStorage.getItem('gridy-resident-language') === 'fil' ? 'fil' : 'en';
        } catch {
            return 'en';
        }
    });

    const setLanguage = useCallback((next: ResidentLanguage) => {
        setLanguageState(next);
        try {
            window.localStorage.setItem('gridy-resident-language', next);
        } catch {
            // The language still applies for the current session if storage is unavailable.
        }
    }, []);

    useEffect(() => {
        document.documentElement.lang = language === 'fil' ? 'fil' : 'en';
    }, [language]);

    const t = useCallback((source: string) => (
        language === 'fil' ? FILIPINO[source] ?? source : source
    ), [language]);

    const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// oxlint-disable-next-line react/only-export-components -- keep provider and its context hook together.
export function useLanguage() {
    return useContext(LanguageContext);
}
